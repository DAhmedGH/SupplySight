CREATE TABLE IF NOT EXISTS SUPPLY_CHAIN_DEV.RAW.INGESTION_BATCHES (
    BATCH_ID VARCHAR NOT NULL,
    SOURCE_SYSTEM VARCHAR NOT NULL,
    STATUS VARCHAR NOT NULL,
    STARTED_AT TIMESTAMP_TZ NOT NULL,
    COMPLETED_AT TIMESTAMP_TZ,
    SOURCE_FILE_COUNT NUMBER(10, 0) NOT NULL DEFAULT 0,
    SOURCE_ROW_COUNT NUMBER(18, 0) NOT NULL DEFAULT 0,
    MERGED_ROW_COUNT NUMBER(18, 0) NOT NULL DEFAULT 0,
    INSERTED_ROW_COUNT NUMBER(18, 0) NOT NULL DEFAULT 0,
    UPDATED_ROW_COUNT NUMBER(18, 0) NOT NULL DEFAULT 0,
