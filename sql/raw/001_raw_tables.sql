-- SupplySight Phase 3 RAW source tables and ingestion audit tables.
-- Source values are stored as VARCHAR to preserve the original CSV representation.
-- Primary keys document business grain. Snowflake does not enforce standard-table keys.

CREATE TABLE IF NOT EXISTS SUPPLY_CHAIN_DEV.RAW.PRODUCTS (
    PRODUCT_ID VARCHAR NOT NULL,
    SKU VARCHAR NOT NULL,
    PRODUCT_NAME VARCHAR NOT NULL,
    CATEGORY VARCHAR NOT NULL,
    SUBCATEGORY VARCHAR,
    UNIT_COST VARCHAR NOT NULL,
    LIST_PRICE VARCHAR NOT NULL,
    LAUNCH_DATE VARCHAR NOT NULL,
    ACTIVE_FLAG VARCHAR NOT NULL,
    REORDER_POINT VARCHAR NOT NULL,
    _INGESTED_AT TIMESTAMP_TZ NOT NULL,
    _SOURCE_FILE VARCHAR NOT NULL,
    _BATCH_ID VARCHAR NOT NULL,
    _SOURCE_SYSTEM VARCHAR NOT NULL,
    _ROW_HASH VARCHAR NOT NULL,
    _QUALITY_STATUS VARCHAR NOT NULL,
    _QUALITY_ISSUES ARRAY,
    PRIMARY KEY (PRODUCT_ID)
);

